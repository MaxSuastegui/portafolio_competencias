def residual_report(residuals: pd.Series, name="res"):
    r = residuals.dropna().copy()
    print(f"\n=== Residuals: {name} ===")
    print("Media:", float(r.mean()), "| Std:", float(r.std()))

    n = len(r)
    if n < 5:
        print(f"Serie de residuales muy corta (n={n}); se omite Ljung-Box.")
    else:
        # Definir lags de forma segura (no mayores que n-2)
        candidate_lags = [7, 14, 21]
        safe_lags = sorted(set([L for L in candidate_lags if 1 <= L <= max(1, n-2)]))
        if not safe_lags:
            print(f"No hay lags válidos para Ljung-Box con n={n}.")
        else:
            for L in safe_lags:
                try:
                    # auto_lag=False evita re-cálculos que causan conflictos de tamaño
                    lb = acorr_ljungbox(r, lags=L, return_df=True, auto_lag=False)
                    pval = float(lb["lb_pvalue"].iloc[-1])
                    print(f"Ljung-Box (lags={L}) p-value = {pval:.4f}")
                except Exception as e:
                    print(f"Ljung-Box (lags={L}) falló: {e}")

    # Errores por día de semana / mes (si el índice es datetime)
    if isinstance(r.index, pd.DatetimeIndex):
        df_tmp = r.to_frame("res")
        df_tmp["dow"] = df_tmp.index.dayofweek
        df_tmp["month"] = df_tmp.index.month
        mae_dow = df_tmp.groupby("dow")["res"].apply(lambda s: np.mean(np.abs(s))).round(2)
