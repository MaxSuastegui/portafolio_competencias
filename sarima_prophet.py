def error_by_group(df_h, group_col, target=TARGET):
    # Real por grupo
    real_g = df_h.groupby([DATE_COL, group_col])[target].sum()
    real_tot = real_g.groupby(level=0).sum()
    # Distribuir las predicciones totales del modelo a cada grupo según “share” histórico (train_full)
    hist = df[df[DATE_COL].lt(test_final.index.min())].copy()
    shares = (hist.groupby([group_col])[target].sum() / hist[target].sum()).replace([np.inf, -np.inf], np.nan).fillna(0.0)
    # pred distribuida por grupo (proporcional a share global histórico)
    pred_ens_by_g = pd.concat([pred_df["ens"]] * len(shares), axis=1)
    pred_ens_by_g.columns = shares.index
    pred_ens_by_g = pred_ens_by_g.mul(shares.values, axis=1)
    # Métrica por grupo (MAE % de su total en holdout)
    out = []
    for g, real_series in real_g.groupby(level=1):
        # Alinear con pred distribuido
        pred_g = pred_ens_by_g[g].reindex(real_series.index.get_level_values(0))
        y_true = real_series.groupby(level=0).sum().reindex(pred_g.index).fillna(0)
        m = metrics_dict(y_true, pred_g)
        out.append({"grupo": g, **m})
    return pd.DataFrame(out).sort_values("MAPE_%", ascending=False)

