from typing import List, Dict, Tuple
from dataclasses import dataclass

def metrics_dict(y_true, y_pred):
    y_true, y_pred = y_true.align(y_pred, join="inner")
    mae  = mean_absolute_error(y_true, y_pred)
    rmse = mean_squared_error(y_true, y_pred) ** 0.5
    mape = (np.abs((y_true - y_pred) / np.maximum(1e-8, y_true))).mean() * 100
    return {"MAE": mae, "RMSE": rmse, "MAPE_%": mape}

def seasonal_naive(train, horizon, season=SEASON):
    idx = pd.date_range(train.index[-1] + pd.Timedelta(days=1), periods=horizon, freq=train.index.freq)
    preds = []
    for d in idx:
        prev = d - pd.Timedelta(days=season)
        preds.append(train.get(prev, train.iloc[-1]))
    return pd.Series(preds, index=idx, name="naive")

@dataclass
class FoldResult:
    fold: int
    start: pd.Timestamp
    end: pd.Timestamp
    metrics: Dict[str, float]
    pred: pd.Series

def rolling_origin_folds(series: pd.Series, n_folds: int, horizon: int, min_train: int) -> List[Tuple[pd.Series, pd.Series]]:
    """Genera (train, test) para CV temporal incremental."""
    folds = []
    n = len(series)
    # tamaño aproximado de paso
    step = max(1, (n - min_train - horizon) // max(1, (n_folds)))
    anchor = min_train
    for i in range(n_folds):
        train_end = anchor + i*step
        if train_end + horizon > n: break
        train = series.iloc[:train_end]
        test  = series.iloc[train_end:train_end + horizon]
        if len(train) >= min_train and len(test) == horizon:
            folds.append((train, test))
    return folds

from statsmodels.tsa.statespace.sarimax import SARIMAX

# Grilla pequeña pero informativa (ajústala si tienes tiempo)
sarima_grid = [
    ((1,1,1), (1,1,1,SEASON)),
    ((0,1,1), (0,1,1,SEASON)),
    ((1,1,0), (1,1,0,SEASON)),
]

def fit_forecast_sarima(train, horizon, order, seasonal_order):
    model = SARIMAX(train, order=order, seasonal_order=seasonal_order,
                    enforce_stationarity=False, enforce_invertibility=False)
    res = model.fit(disp=False)
    fc = res.get_forecast(steps=horizon)
    mean = fc.predicted_mean
    conf = fc.conf_int(alpha=0.20)  # 80% CI (ajústalo a 95% si prefieres)
    return mean, conf  # (pred, intervalos)

def tune_sarima_cv(series: pd.Series, n_folds=4, horizon=14, min_train=MIN_OBS):
    folds = rolling_origin_folds(series, n_folds, horizon, min_train)
    results = []
    for order, seas in sarima_grid:
        fold_metrics = []
        preds_all = []
        for k,(train,test) in enumerate(folds, start=1):
            pred, conf = fit_forecast_sarima(train, len(test), order, seas)
            m = metrics_dict(test, pred)
            fold_metrics.append(m)
            preds_all.append(pred.rename(f"fold{k}"))
        avg = pd.DataFrame(fold_metrics).mean().to_dict()
        results.append({"order":order, "seas":seas, "avg_metrics":avg, "folds":fold_metrics})
    # elige por MAPE
    best = sorted(results, key=lambda r: r["avg_metrics"]["MAPE_%"])[0]
    return best, results

from prophet import Prophet

# Grilla corta de Prophet: mode + weekly + changepoint_prior_scale
prophet_grid = [
    {"seasonality_mode":"additive", "weekly_seasonality":True,  "changepoint_prior_scale":0.05},
    {"seasonality_mode":"multiplicative", "weekly_seasonality":True, "changepoint_prior_scale":0.05},
    {"seasonality_mode":"multiplicative", "weekly_seasonality":True, "changepoint_prior_scale":0.2},
]

def fit_forecast_prophet(train, horizon, params):
    dfp = train.reset_index().rename(columns={train.index.name or "index":"ds", train.name or TARGET:"y"})
    m = Prophet(daily_seasonality=True,
                weekly_seasonality=params.get("weekly_seasonality", True),
                yearly_seasonality=False,
                seasonality_mode=params.get("seasonality_mode","additive"),
                changepoint_prior_scale=params.get("changepoint_prior_scale",0.05))
    m.fit(dfp)
    future = m.make_future_dataframe(periods=horizon, freq="D")
    fcst = m.predict(future).set_index("ds")
    pred = fcst["yhat"].iloc[-horizon:]
    # Prophet ya trae intervalos yhat_lower / yhat_upper
    conf = fcst[["yhat_lower","yhat_upper"]].iloc[-horizon:]
    return pred, conf

def tune_prophet_cv(series: pd.Series, n_folds=4, horizon=14, min_train=MIN_OBS):
    folds = rolling_origin_folds(series, n_folds, horizon, min_train)
    results = []
    for params in prophet_grid:
        fold_metrics = []
        for k,(train,test) in enumerate(folds, start=1):
            pred, conf = fit_forecast_prophet(train, len(test), params)
            m = metrics_dict(test, pred)
            fold_metrics.append(m)
        avg = pd.DataFrame(fold_metrics).mean().to_dict()
        results.append({"params":params, "avg_metrics":avg, "folds":fold_metrics})
    best = sorted(results, key=lambda r: r["avg_metrics"]["MAPE_%"])[0]
    return best, results

